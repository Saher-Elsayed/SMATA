class ITestAdapter(ABC):
    """
    Abstract interface for SMATA test-generation back-ends.

    All adapters (Monkey, Dynodroid, Espresso, XCUITest, etc.)
    must implement this interface to be pluggable into the Driver.
    """

    @abstractmethod
    def initialize(self, app_package: str, config: AdapterConfig) -> None:
        """Initialize the adapter for the given app."""
        ...

    @abstractmethod
    def execute(self, duration_seconds: int) -> TestRunResult:
        """Execute a test run for the given duration."""
        ...

    @abstractmethod
    def get_adapter_name(self) -> str:
        """Return the adapter's display name."""
        ...

    @abstractmethod
    def get_event_count(self) -> int:
        """Return current event count generated this session."""
        ...

    @abstractmethod
    def stop(self) -> None:
        """Gracefully stop the current run."""
        ...

    def get_current_coverage(self) -> float:
        """Return current statement coverage (0.0-100.0)."""
        return 0.0

    def get_visited_activities(self) -> List[str]:
        """Return list of visited Android activities / iOS view controllers."""
        return []

    def is_running(self) -> bool:
        """Return True if the adapter is currently executing."""
        return False

    def __repr__(self) -> str:
        return f"{self.__class__.__name__}(name={self.get_adapter_name()})"


class IMonitor(ABC):
    """Abstract interface for SMATA monitor components."""

    @abstractmethod
    def start_recording(self) -> None:
        ...

    @abstractmethod
    def stop_recording(self) -> None:
        ...

    @abstractmethod
    def get_event_count(self) -> int:
        ...


class ISequencer(ABC):
    """Abstract interface for SMATA sequencer components."""

    @abstractmethod
    def initialize(self, app_package: str) -> bool:
        ...

    @abstractmethod
    def load_script_library(self, path: str) -> None:
        ...


class IChecker(ABC):
    """Abstract interface for SMATA checker/sanity-check components."""

    @abstractmethod
    def check(self) -> Optional[BugReport]:
        ...

    @abstractmethod
    def get_bug_reports(self) -> List[BugReport]:
        ...
